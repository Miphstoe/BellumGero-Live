ROOT = g.ROOT
FURNITURE_GOT = 8203  # SceneObjectType::FURNITURE — makes a generic tangible placeable/movable in structures


def read(rel):
    return open(os.path.join(ROOT, *rel.split('/')), encoding='utf-8', newline='').read()


def body(text):
    """Drop the GPL header: keep from the first template definition on."""
    i = text.find('object_')
    return text[i:] if i > 0 else text


def write(rel, text):
    return g.write(rel, text)


def luaid(client_path):
    return client_path[:-4].replace('/', '_')


def server_path(client_path):
    d, f = client_path.rsplit('/', 1)
    assert f.startswith('shared_'), client_path
    return f'{d}/{f[7:]}'


# ---------------------------------------------------------------- shared (client) template defs in objects.lua files
SHARED_KIND = {'object/draft_schematic/': 'SharedDraftSchematicObjectTemplate', 'object/intangible/': 'SharedIntangibleObjectTemplate',
               'object/mobile/': 'SharedCreatureObjectTemplate'}


def shared_block(client_path):
    kind = next((v for k, v in SHARED_KIND.items() if client_path.startswith(k)), 'SharedTangibleObjectTemplate')
    lid = luaid(client_path)
    return f'{lid} = {kind}:new {{\n\tclientTemplateFileName = "{client_path}"\n}}\n\nObjectTemplates:addClientTemplate({lid}, "{client_path}")\n'


def ensure_shared(objects_lua_rel, client_paths):
    """Append shared defs that are not yet in an existing objects.lua."""
    path = os.path.join(ROOT, *objects_lua_rel.split('/'))
    s = open(path, encoding='utf-8', newline='').read()
    nl = '\r\n' if '\r\n' in s else '\n'
    add = [p for p in client_paths if luaid(p) + ' =' not in s and f'"{p}"' not in s]
    if add:
        s = s.rstrip('\r\n') + nl + nl + nl.join(shared_block(p).replace('\n', nl) for p in add)
        open(path, 'w', encoding='utf-8', newline='').write(s)
    return len(add)


def new_dir(dir_rel, allobjects_anchor, parent_serverobjects, shared_paths, files):
    """Create <dir>/objects.lua + serverobjects.lua and register both."""
    write(f'{dir_rel}/objects.lua', '-- Generated by NewPlanets/gen_hoth_loot.py\n' + '\n'.join(shared_block(p) for p in shared_paths))
    write(f'{dir_rel}/serverobjects.lua', ''.join(f'includeFile("{dir_rel[7:]}/{f}")\n' for f in files))
    g.register('object/allobjects.lua', f'includeFile("{dir_rel[7:]}/objects.lua")', after_prefix=allobjects_anchor)
    g.register(parent_serverobjects, f'includeFile("{dir_rel[7:]}/serverobjects.lua")')


