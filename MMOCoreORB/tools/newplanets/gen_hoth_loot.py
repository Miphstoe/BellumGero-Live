def weights(items):
    """Distribute 10,000,000 over items; items may be (name, relative weight) tuples."""
    items = [(i, 1) if isinstance(i, str) else i for i in items]
    tot = sum(w for _, w in items)
    out = [(n, 10000000 * w // tot) for n, w in items]
    out[-1] = (out[-1][0], 10000000 - sum(w for _, w in out[:-1]))
    return out


