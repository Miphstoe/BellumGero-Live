def snapshot_tops():
    _, nodes = mo.ws_nodes(open(SNAPSHOT, 'rb').read())
    return [n for n in nodes if n['pid'] == 0]


def footprint(tmpl):
    if 'starport' in tmpl:
        return 42.0
    if '/building/' in tmpl:
        return 30.0 if any(k in tmpl for k in ('cantina', 'hospital', 'cloning', 'guild', 'garage')) else 18.0
    if '/installation/' in tmpl or 'mockup_' in tmpl:
        return 9.0
    return 2.5


class Placer:
    """Hands out free outdoor spots around a centre, avoiding snapshot objects and each other."""

    def __init__(self, tops):
        self.obstacles = [(n['x'], n['y'], footprint(n['tmpl'])) for n in tops]
        self.taken = []

    def free(self, x, y, clearance):
        if any(math.hypot(x - ox, y - oy) < r + clearance for ox, oy, r in self.obstacles):
            return False
        return all(math.hypot(x - tx, y - ty) >= 2.5 for tx, ty in self.taken)

    def spots(self, cx, cy, n, rmin, rmax, clearance=1.5):
        out = []
        r = rmin
        while len(out) < n and r <= rmax:
            steps = max(8, int(2 * math.pi * r / 4.0))
            for i in range(steps):
                a = 2 * math.pi * (i + (r % 3) / 3.0) / steps
                x, y = round(cx + r * math.sin(a), 1), round(cy + r * math.cos(a), 1)
                if self.free(x, y, clearance):
                    self.taken.append((x, y))
                    heading = int(round(math.degrees(math.atan2(cx - x, cy - y))))  # face the centre
                    out.append((x, y, heading))
                    if len(out) == n:
                        break
            r += 4.0
        assert len(out) == n, f'only {len(out)}/{n} free spots near ({cx}, {cy}) within {rmax} m'
        return out


