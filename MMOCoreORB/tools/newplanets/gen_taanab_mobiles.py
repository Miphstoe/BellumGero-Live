def write(rel, text):
    path = os.path.join(ROOT, *rel.split('/'))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    return rel


def register(rel_list_file, line, after_prefix=None):
    """Add an includeFile line to a list file if it is not there yet (after the last line starting with after_prefix)."""
    path = os.path.join(ROOT, *rel_list_file.split('/'))
    s = open(path, encoding='utf-8', newline='').read()
    if line in s:
        return False
    nl = '\r\n' if '\r\n' in s else '\n'
    if after_prefix:
        lines = s.split(nl)
        idx = max(i for i, l in enumerate(lines) if l.startswith(after_prefix))
        lines.insert(idx + 1, line)
        s = nl.join(lines)
    else:
        s = s.rstrip('\r\n') + nl + line + nl
    open(path, 'w', encoding='utf-8', newline='').write(s)
    return True


